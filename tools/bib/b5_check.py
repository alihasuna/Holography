_YOON = {"ャ": "a", "ュ": "u", "ョ": "o"}


def kana_to_hepburn(s):
    """Plain Hepburn transcription of a katakana reading (no macrons), e.g. タケグチ -> Takeguchi."""
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c in _KANA:
            syl = _KANA[c]
            if i + 1 < len(s) and s[i + 1] in _YOON:
                syl = syl[:-1] + ("" if syl in ("shi", "chi", "ji") else "y") + _YOON[s[i + 1]]
                i += 1
            out.append(syl)
        elif c == "ッ" and i + 1 < len(s) and s[i + 1] in _KANA:
            out.append(_KANA[s[i + 1]][0])
        elif c == "ー":
            pass
        else:
            out.append(c)
        i += 1
    return "".join(out)


def kana_name(k):
    fam, _, giv = k.partition(",")
    return kana_to_hepburn(fam.strip()).capitalize(), kana_to_hepburn(giv.strip()).capitalize()


