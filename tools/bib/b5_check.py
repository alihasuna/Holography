def verdict_takeguchi(r, e, base):
    """Apply the proposed correction only if CiNii/NDL confirms it (task instruction)."""
    old = next(b for b in base if b.key == "TAKEGUCHI1990")
    crm = crossref_msg("TAKEGUCHI1990.json")
    loc, url = oup_locator(crm)
    cin = [m for m in r["mism"] if m["source"] == "CiNii" and m["kind"] not in NONCOUNT]
    cr = [m for m in r["mism"] if m["source"] == "Crossref" and m["kind"] not in NONCOUNT]
    tests = {"CiNii": "confirms author list, title, journal, volume, issue, pages, year" if not cin else json.dumps(cin),
             "Crossref": "title, journal, year agree; record has no authors, volume or pages" if not cr else json.dumps(cr),
             "locator": f"{loc} in {url}"}
    ok = not cin and not cr and loc == (e.get("volume"), e.get("number"), bib_first_page(e))
    r["takeguchi"] = {"old": {f.name: f.value for f in old.fields if f.name != "note"}, "tests": tests, "ok": ok}
    if ok:
        return {"verdict": "CORRECTION-CONFIRMED", "action": "references.bib [TAKEGUCHI1990] corrected and moved "
                                                              "from the UNVERIFIED section"}
    return {"verdict": "CORRECTION-NOT-CONFIRMED", "action": "references.bib [TAKEGUCHI1990] left unchanged"}


