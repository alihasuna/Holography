def jload(name):
    p = CACHE / name
    return json.loads(p.read_text()) if p.exists() else None


def crossref_msg(name):
    d = jload(name)
    return d["message"] if d else None


def _pick(lst, field, lang="en"):
    lst = lst or []
    for x in lst:
        if x.get("lang") == lang and x.get(field):
            return x[field]
    for x in lst:
        if x.get(field) and not x.get("lang"):
            return x[field]
    return lst[0].get(field) if lst else None


def jalc_msg(key):
    """JaLC record -> a Crossref-shaped message (English values preferred), for crossref_check.compare."""
    d = jload(f"{key}.jalc.json")
    if not d or d.get("status") != "OK":
        return None
    a = d["data"]
    names = []
    for c in sorted(a.get("creator_list") or [], key=lambda c: int(c.get("sequence", 0))):
        ns = c.get("names") or []
        n = next((x for x in ns if x.get("lang") == "en"), ns[0] if ns else {})
        names.append({"family": n.get("last_name", n.get("first_name", "")) if n.get("last_name") else
                      n.get("first_name", ""), "given": n.get("first_name", "") if n.get("last_name") else ""})
    journal = None
    for j in a.get("journal_title_name_list") or []:
        if j.get("type") == "full" and j.get("lang") == "en":
            journal = j["journal_title_name"]
            break
    if journal is None:
        journal = _pick(a.get("journal_title_name_list"), "journal_title_name")
    pd = a.get("publication_date") or {}
    parts = [int(pd[k]) for k in ("publication_year", "publication_month", "publication_day") if pd.get(k)]
    fp, lp = a.get("first_page"), a.get("last_page")
    msg = {"DOI": a["doi"], "type": "jalc:" + a.get("content_type", ""),
           "title": [_pick(a.get("title_list"), "title") or ""],
           "author": [{"family": n["family"], "given": n["given"]} for n in names],
           "container-title": [journal] if journal else [],
           "publisher": _pick(a.get("publisher_list"), "publisher_name") or "",
           "issued": {"date-parts": [parts]} if parts else {}}
    if a.get("volume"):
        msg["volume"] = a["volume"]
    if a.get("issue"):
        msg["issue"] = a["issue"]
    if fp:
        msg["page"] = f"{fp}-{lp}" if lp and lp != fp else fp
    msg["_ja_title"] = _pick(a.get("title_list"), "title", "ja")
    return msg


def _xml_tag(t, tag):
    return [html.unescape(re.sub(r"\s+", " ", x)).strip()
            for x in re.findall(rf"<{tag}(?:\s[^>]*)?>(.*?)</{tag}>", t, re.S)]


def arxiv_msg(key):
    """arXiv OAI-PMH records (arXiv + arXivRaw) -> Crossref-shaped message plus arXiv extras."""
    p, r = CACHE / f"{key}.oai-arxiv.xml", CACHE / f"{key}.oai-arxivraw.xml"
    if not p.exists():
        return None
    t = p.read_text()
    if "<GetRecord>" not in t:
        return None
    t = t[t.index("<metadata>"):]
    authors = []
    for a in re.findall(r"<author>(.*?)</author>", t, re.S):
        authors.append({"family": (_xml_tag(a, "keyname") or [""])[0],
                        "given": (_xml_tag(a, "forenames") or [""])[0]})
    created = _xml_tag(t, "created")[0]
    msg = {"type": "arxiv", "title": [_xml_tag(t, "title")[0]], "author": authors,
           "issued": {"date-parts": [[int(x) for x in created.split("-")]]},
           "_id": _xml_tag(t, "id")[0], "_categories": (_xml_tag(t, "categories") or [""])[0],
           "_doi": (_xml_tag(t, "doi") or [None])[0], "_journal_ref": (_xml_tag(t, "journal-ref") or [None])[0],
           "_versions": []}
    if r.exists():
        rt = r.read_text()
        for v, date in re.findall(r'<version version="(v\d+)">\s*<date>(.*?)</date>', rt, re.S):
            msg["_versions"].append((v, dt.datetime.strptime(date.strip(), "%a, %d %b %Y %H:%M:%S %Z")
                                     .strftime("%Y-%m-%d")))
    return msg


def cinii_msg(key):
    d = jload(f"{key}.cinii.json")
    if not d:
        return None
    title = next((x["@value"] for x in d.get("dc:title", []) if x.get("@language") in (None, "ja", "en")), "")
    authors, kana = [], []
    for c in d.get("creator", []):
        nm = c.get("foaf:name", [])
        plain = next((x["@value"] for x in nm if x.get("@language") != "ja-Kana"), "")
        kana.append(next((x["@value"] for x in nm if x.get("@language") == "ja-Kana"), ""))
        if "," in plain:
            fam, giv = [s.strip() for s in plain.split(",", 1)]
        else:
            toks = plain.split()
            if len(toks) > 1 and toks[0].isupper() and not toks[-1].isupper():
                # B5: CiNii's NII article records write 'FAMILY Given' (e.g. 'SOSIATI Harini')
                fam, giv = toks[0].capitalize(), " ".join(toks[1:])
            else:
                fam, giv = (toks[-1], " ".join(toks[:-1])) if len(toks) > 1 else (plain, "")
        authors.append({"family": fam, "given": giv})
    msg = {"type": "cinii:" + d.get("@type", ""), "title": [title], "author": authors, "_kana": kana,
           "_crid": d["@id"], "_ids": {i["identifier"]["@type"]: i["identifier"]["@value"]
                                       for i in d.get("productIdentifier", [])}}
    pub = d.get("publication") or {}
    if pub:
        msg["container-title"] = [x["@value"] for x in pub.get("prism:publicationName", [])]
        for a, b in (("prism:volume", "volume"), ("prism:number", "issue")):
            if pub.get(a):
                msg[b] = pub[a]
        sp = (pub.get("prism:startingPage") or "").lstrip("p")
        ep = pub.get("prism:endingPage") or ""
        if sp:
            msg["page"] = f"{sp}-{ep}" if ep else sp
        if pub.get("prism:publicationDate"):
            msg["issued"] = {"date-parts": [[int(x) for x in pub["prism:publicationDate"].split("-")]]}
    if d.get("ndl:dateGranted"):
        msg["issued"] = {"date-parts": [[int(x) for x in d["ndl:dateGranted"].split("-")]]}
        msg["_degree"] = (d.get("ndl:degreeName"), d.get("ndl:dissertationNumber"),
                          [x["@value"] for x in (d.get("degreeAwardInstitution") or {}).get("jpcoar:degreeGrantorName", [])])
    return msg


