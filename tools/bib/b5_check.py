def http_get_full(url, accept="*/*", tries=3):
    """GET with redirects followed; returns (status, body, final_url, content_type)."""
    import time
    import urllib.error
    import urllib.request
    last = (None, b"", url, "")
    for n in range(tries):
        req = urllib.request.Request(url, headers={"User-Agent": cc.UA, "Accept": accept})
        try:
            with urllib.request.urlopen(req, timeout=90) as r:
                return r.status, r.read(), r.geturl(), r.headers.get("Content-Type", "")
        except urllib.error.HTTPError as exc:
            last = (exc.code, b"", url, exc.headers.get("Content-Type", "") if exc.headers else "")
            if exc.code not in (429, 500, 502, 503, 504):
                return last
        except Exception as exc:  # network error
            last = (None, str(exc).encode(), url, "")
        time.sleep(2 * (n + 1))
    return last


def html_text(body):
    t = body.decode("utf-8", "replace")
    t = re.sub(r"(?is)<(script|style|noscript)\b.*?</\1>", " ", t)
    title = _xml_tag(t, "title")
    h1 = [re.sub(r"<[^>]+>", " ", x) for x in re.findall(r"(?is)<h1\b[^>]*>(.*?)</h1>", t)]
    txt = html.unescape(re.sub(r"<[^>]+>", " ", t))
    return (re.sub(r"\s+", " ", txt).strip(), (title or [""])[0],
            [re.sub(r"\s+", " ", html.unescape(x)).strip() for x in h1])


def pdf_pages_text(body):
    """[(page number, text)] with pymupdf (else pypdf); plus metadata title / creation date and page count."""
    try:
        import pymupdf
        d = pymupdf.open(stream=body, filetype="pdf")
        meta = d.metadata or {}
        pages = [(i + 1, d[i].get_text()) for i in range(d.page_count)]
        return pages, {"pages": d.page_count, "title": meta.get("title") or "",
                       "subject": meta.get("subject") or "", "creationDate": meta.get("creationDate") or "", "extracted_with": "pymupdf"}
    except ImportError:
        import io
        import pypdf
        r = pypdf.PdfReader(io.BytesIO(body))
        m = r.metadata or {}
        return ([(i + 1, pg.extract_text() or "") for i, pg in enumerate(r.pages)],
                {"pages": len(r.pages), "title": m.get("/Title") or "", "creationDate": m.get("/CreationDate") or "",
                 "extracted_with": "pypdf"})


def norm_text(s):
    return re.sub(r"\s+", " ", bt.fold(s.replace("\u00ad", "").replace("-\n", ""))).strip()


def page_expectations(pg, e):
    """[(what, string)]: the declared strings plus, if flagged, the entry's title and author family names."""
    out = []
    if e is not None and pg.get("entry_title"):
        out.append(("entry title", bt.latex_to_unicode(e.get("title") or "").strip()))
    if e is not None and pg.get("authors"):
        for n in bt.split_names(e.get("author") or ""):
            out.append(("author family name", bt.parse_name(n)["family"]))
    return out + [(w, s) for w, s in (pg.get("expect") or [])]


def page_fetch(k, i, pg, idx, refresh=False, e=None):
    """Fetch one page/document of a no-DOI entry; cache only the checks (never the page text)."""
    name = f"{k}.page{i}.json"
    path = CACHE / name
    if path.exists() and not refresh and json.loads(path.read_text()).get("status") == 200:
        return 200
    st, body, final, ctype = http_get_full(pg["url"])
    rec = {"url": pg["url"], "final_url": final, "status": st, "content_type": ctype,
           "fetched_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
    if st == 200:
        rec["sha256"] = hashlib.sha256(body).hexdigest()
        rec["bytes"] = len(body)
        if body[:5] == b"%PDF-" or "pdf" in ctype.lower():
            pages, meta = pdf_pages_text(body)
            rec["pdf"] = meta
        else:
            txt, title, h1 = html_text(body)
            pages = [(1, txt)]
            rec["html_title"], rec["h1"] = re.sub(r"\s+", " ", html.unescape(title)).strip(), h1
        checks = []
        for what, s in page_expectations(pg, e):
            ns = norm_text(s)
            hit = [n for n, tx in pages if ns and ns in norm_text(tx)]
            checks.append({"what": what, "string": s, "found": bool(hit),
                           "on_pages": hit[:5] if rec.get("pdf") else None})
        rec["checks"] = checks
    path.write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n")
    idx[name] = {"url": pg["url"], "status": st, "fetched_utc": rec["fetched_utc"],
                 "stored": str(path.relative_to(ROOT)), "note": "checks only; page text not stored"}
    cc.save_index(idx)
    return st


JSTAGE_META = ("citation_title", "citation_author", "citation_journal_title", "citation_volume", "citation_issue",
               "citation_firstpage", "citation_lastpage", "citation_publication_date", "citation_date", "citation_doi")


def jstage_fetch(k, idx, refresh=False):
    """J-STAGE landing page named in the Crossref record (resource.primary.URL), in its Japanese and English
    views; only the citation_* meta tags are cached (as <KEY>.jstage.json)."""
    name = f"{k}.jstage.json"
    path = CACHE / name
    if path.exists() and not refresh:
        return
    crm = crossref_msg(f"{k}.json")
    url = ((crm.get("resource") or {}).get("primary") or {}).get("URL", "")
    out = {"record_url": url, "views": []}
    for lang in ("ja", "en"):
        u_ = re.sub(r"-char/(ja|en)/?$", f"-char/{lang}/", url) if "-char/" in url else url
        st, body, final, ctype = http_get_full(u_, accept="text/html")
        v = {"url": u_, "final_url": final, "status": st,
             "fetched_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
        if st == 200:
            t = body.decode("utf-8", "replace")
            meta = {}
            for m in re.finditer(r"<meta\s+[^>]*>", t, re.I):
                tag = m.group(0)
                nm = re.search(r'name="([^"]+)"', tag)
                ct = re.search(r'content="([^"]*)"', tag)
                if nm and ct and nm.group(1) in JSTAGE_META:
                    meta.setdefault(nm.group(1), []).append(html.unescape(ct.group(1)).strip())
            v["meta"] = meta
            v["sha256"] = hashlib.sha256(body).hexdigest()
        out["views"].append(v)
        if u_ == url and "-char/" not in url:
            break
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    idx[name] = {"url": url, "status": max((v["status"] or 0) for v in out["views"]),
                 "fetched_utc": out["views"][-1]["fetched_utc"], "stored": str(path.relative_to(ROOT)),
                 "note": "citation_* meta tags of the J-STAGE landing page (ja and en views)"}
    cc.save_index(idx)


