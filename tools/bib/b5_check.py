    L += ["", "Differences not counted as mismatches (the record is silent on the field, or white space only):", ""]
    for r in results:
        for m in r["mism"]:
            if m["kind"] in NONCOUNT:
                L.append(f"* {r['key']}: {m['field']} proposal '{md(m['proposal'])}', {m['source']} record "
                         f"'{md(m['record'])}' ({m['kind']})")
