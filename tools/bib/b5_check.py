def first_family(e):
    names = bt.split_names(e.get("author") or "")
    if not names:
        return ""
    fam = bt.parse_name(names[0]).get("family", "")
    if "(" in names[0]:                                  # 'kanji, kanji (Roman, Name)'
        m = re.search(r"\(([^,()]+),", names[0])
        fam = m.group(1) if m else fam
    return bt.fold(fam)


def same_work(a, b):
    """Title similarity if a and b could be one work (same first-author family name); 0 otherwise."""
    ta, tb = bt.fold(a.get("title") or ""), bt.fold(b.get("title") or "")
    if not ta or not tb:
        return 0.0
    r = difflib.SequenceMatcher(None, ta, tb).ratio()
    return r if first_family(a) and first_family(a) == first_family(b) else 0.0


def distinct_items(a, b):
    """Two differently registered DOIs, or different years: separate items even if the titles agree
    (e.g. a meeting abstract and the later paper of the same title)."""
    da, db = (a.get("doi") or "").lower(), (b.get("doi") or "").lower()
    return bool(da and db and da != db) or (a.get("year") and b.get("year") and a.get("year") != b.get("year"))


def find_duplicates(props, base):
    """{key: (kind, other_key, detail)} against the baseline bib and between the proposals."""
    out, near = {}, []
    bdoi = {(e.get("doi") or "").lower(): e.key for e in base if e.get("doi")}
    barx = {arxiv_id(e): e.key for e in base if arxiv_id(e)}
    bkey = {e.key.lower(): e for e in base}
    for src, e in props:
        d = (e.get("doi") or "").lower()
        if e.key.lower() in bkey and not (d and d == (bkey[e.key.lower()].get("doi") or "").lower()):
            out[e.key] = ("references.bib", bkey[e.key.lower()].key, "same key, different item (key collision)")
        elif d and d in bdoi:
            out[e.key] = ("references.bib", bdoi[d], "same DOI")
        elif arxiv_id(e) and arxiv_id(e) in barx:
            out[e.key] = ("references.bib", barx[arxiv_id(e)], "same arXiv id")
        else:
            for b in base:
                r = same_work(e, b)
                if r >= 0.90 and distinct_items(e, b):
                    near.append((e.key, b.key, round(r, 2), "same first author and title but "
                                 + ("different DOI" if e.get("doi") and b.get("doi") else "different year")
                                 + f" ({e.get('year')} vs {b.get('year')}): separate item, not a duplicate"))
                elif r >= 0.90:
                    out[e.key] = ("references.bib", b.key, f"same first author, title similarity {r:.2f}")
                    break
                elif r >= 0.60:
                    near.append((e.key, b.key, round(r, 2), "related title, same first author"))
    for i, (sa, a) in enumerate(props):
        for sb, b in props[i + 1:]:
            if sa == sb:
                continue
            da, db = (a.get("doi") or "").lower(), (b.get("doi") or "").lower()
            why = "same DOI" if da and da == db else (
                "same arXiv id" if arxiv_id(a) and arxiv_id(a) == arxiv_id(b) else None)
            r = same_work(a, b)
            if not why and distinct_items(a, b):
                r = min(r, 0.89)
            if why or r >= 0.90:
                why = why or f"same first author, title similarity {r:.2f}"
                out.setdefault(b.key, (sa, a.key, why))
                out.setdefault(a.key, (sb, b.key, why))
            elif r >= 0.60:
                near.append((a.key, b.key, round(r, 2), "related title, same first author (L8 vs L9)"))
    return out, near


