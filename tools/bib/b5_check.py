def cmd_fetch(args):
    routes = load_routes()
    idx = cc.load_index()
    want = set(args.keys)
    for src, e in proposals():
        k = e.key
        if want and k not in want:
            continue
        doi = e.get("doi")
        if doi:
            st, _ = cc.cached_get(f"{k}.json", cc.works_url(doi), idx, args.refresh)
            print(f"{src} {k}: Crossref /works {st}")
            if st == 404:
                st2, body = cc.cached_get(f"{k}.ra.json", "https://doi.org/ra/" + doi, idx, args.refresh)
                ra = json.loads(body)[0].get("RA") if st2 == 200 else None
                print(f"   doi.org/ra {st2}: {ra}")
                if ra == "JaLC":
                    st3, _ = cc.cached_get(f"{k}.jalc.json", jalc_url(doi), idx, args.refresh)
                    print(f"   JaLC {st3}")
                elif ra == "DataCite":
                    st3, _ = cc.cached_get(f"{k}.datacite.json",
                                           "https://api.datacite.org/dois/" + urllib.parse.quote(doi, safe=""),
                                           idx, args.refresh)
                    print(f"   DataCite {st3}")
        aid = arxiv_id(e)
        if aid:
            st, _ = cc.cached_get(f"{k}.arxiv.xml", "https://export.arxiv.org/api/query?id_list=" + aid, idx,
                                  args.refresh, accept="*/*")
            print(f"   arXiv query API {st}")
            for pfx in ("arXiv", "arXivRaw"):
                url = ("https://oaipmh.arxiv.org/oai?verb=GetRecord&identifier=oai:arXiv.org:" + aid
                       + "&metadataPrefix=" + pfx)
                st, _ = cc.cached_get(f"{k}.oai-{pfx.lower()}.xml", url, idx, args.refresh, accept="*/*")
                print(f"   arXiv OAI-PMH {pfx} {st}")
            am = arxiv_msg(k)
            x0 = (load_routes().get("extra") or {}).get(k) or {}
            if am and am["_doi"] and am["_doi"].lower() not in ((doi or "").lower(), (x0.get("claim_doi") or "").lower()):
                st, _ = cc.cached_get(f"{k}.arxivdoi.json", cc.works_url(am["_doi"]), idx, args.refresh)
                print(f"   Crossref /works of the DOI in the arXiv record {am['_doi']}: {st}")
        x = (routes.get("extra") or {}).get(k) or {}
        if x.get("cinii"):
            st, _ = cc.cached_get(f"{k}.cinii.json", f"https://cir.nii.ac.jp/crid/{x['cinii']}.json", idx,
                                  args.refresh)
            print(f"   CiNii {x['cinii']} {st}")
        if x.get("claim_doi"):
            st, _ = cc.cached_get(f"{k}.claim.json", cc.works_url(x["claim_doi"]), idx, args.refresh)
            print(f"   Crossref /works of the DOI claimed in the report {x['claim_doi']}: {st}")
        if x.get("alt_doi"):
            st, _ = cc.cached_get(f"{k}.altdoi.json", cc.works_url(x["alt_doi"]), idx, args.refresh)
            print(f"   Crossref /works of the second DOI named in the note {x['alt_doi']}: {st}")
        if x.get("europepmc") and doi:
            url = ("https://www.ebi.ac.uk/europepmc/webservices/rest/search?query="
                   + urllib.parse.quote(f'DOI:"{doi}"') + "&resultType=core&format=json")
            st, _ = cc.cached_get(f"{k}.epmc.json", url, idx, args.refresh)
            print(f"   Europe PMC core record by DOI {st}")
        if x.get("jstage"):
            jstage_fetch(k, idx, args.refresh)
        if x.get("crossref_query"):
            url = (cc.CROSSREF + "?query.bibliographic=" + urllib.parse.quote(x["crossref_query"])
                   + "&rows=5&select=DOI,title,author,container-title,issued,page,volume,type")
            st, _ = cc.cached_get(f"{k}.crquery.json", url, idx, args.refresh)
            print(f"   Crossref bibliographic query {st}")
        for i, pg in enumerate(x.get("page") or [], 1):
            st = page_fetch(k, i, pg, idx, args.refresh, e)
            print(f"   page {i} {pg['url']} -> {st}")
