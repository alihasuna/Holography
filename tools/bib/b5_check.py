def unicodedata_nfkc(s):
    import unicodedata
    return unicodedata.normalize("NFKC", s or "").strip()


def oup_locator(msg):
    """(volume, issue, first page) encoded in an academic.oup.com resource/link URL of a Crossref record."""
    urls = [((msg.get("resource") or {}).get("primary") or {}).get("URL", "")]
    urls += [l.get("URL", "") for l in msg.get("link") or []]
    for u_ in urls:
        m = re.search(r"academic\.oup\.com/\w+/article(?:-pdf)?/(\d+)/(\d+)/(\d+)/", u_ or "")
        if m:
            return m.groups(), u_
    return None, None


