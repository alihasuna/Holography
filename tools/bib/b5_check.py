#!/usr/bin/env python3
"""B5 -- independent verification of the L8 and L9 bibliography proposals and their merge.

Copied from tools/bib/b4_check.py (B4, 2026-09-23) and adapted; b4_check.py itself is unchanged.

Inputs: docs/agent_reports/L8_new_refs.bib, docs/agent_reports/L9_new_refs.bib (never edited),
tools/bib/b5_routes.yaml (extra routes and declared decisions), the committed record cache
docs/agent_reports/crossref_cache/ and the baseline references.bib at `baseline_rev`.

Subcommands (paths resolved from the repository root):

  fetch     for every proposed entry: GET https://api.crossref.org/works/<DOI> (no mailto parameter,
            no personal data; User-Agent "Holography-bibcheck/1.0"); on 404, GET https://doi.org/ra/<DOI>
            and, for JaLC DOIs, https://api.japanlinkcenter.org/dois/<DOI>, for DataCite DOIs
            https://api.datacite.org/dois/<DOI>.  arXiv ids: the arXiv query API and arXiv's OAI-PMH
            interface (metadataPrefix arXiv and arXivRaw).  Extra routes from b5_routes.yaml: CiNii
            Research record JSON, Europe PMC core record by DOI, the Crossref record of a second DOI named
            in a note, the J-STAGE landing page named in the Crossref record (citation_* meta tags), a
            Crossref bibliographic query for items without a DOI (logged, never used to add a DOI unless
            declared), and -- for web pages, slides, manufacturer and company documents without any
            registry record -- the page itself: HTTP status, final URL, SHA-256, the page's <title>/<h1>
            (HTML) or title metadata and page count (PDF), and whether each expected string (the entry's
            title and owner, declared in b5_routes.yaml) occurs in the page text.  Page text is NOT stored
            (facility pages and slides carry staff contacts); only the checks are cached, as
            docs/agent_reports/crossref_cache/<KEY>.page<N>.json.  Every response is indexed in
            _index.json with URL, HTTP status and fetch time.
  report    compare every proposal field by field with its record(s); detect duplicates against the
            baseline references.bib (same DOI, same arXiv id, same key, or same work = same first-author
            family name and title similarity >= 0.90) and between L8 and L9; check the bibliographic
            fields that the L8/L9 report texts print next to each DOI; check that every citation key
            used in docs/*.md and docs/source_map.tsv exists in references.bib; write
            docs/agent_reports/B5_results.tsv and the generated block of B5_verification_log.md.
  merge     rebuild docs/references.bib = baseline + the verified, deduplicated entries (fields copied
            from the records; for no-DOI items the proposal's fields as checked on the page).
            Idempotent: always starts from the baseline revision, and refuses to write if the current
            file carries edits other than B5's own.
  validate  crossref_check.py validate (balanced braces, unique keys, notes, doi shape, no doi in the
            UNVERIFIED section, every doi backed by a cached registry record -- Crossref, DataCite or JaLC).
"""
