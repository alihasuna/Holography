PERIOD_TOL_A = 1e-6               # extents must be integer numbers of in-plane periods
HEIGHT_MAP_GRID_A = 0.25          # sampling of the (e) height-map grid (numerical choice)
HEIGHT_MAP_PAD_A = 8.0            # grid extends this far beyond the ring's outer radius
