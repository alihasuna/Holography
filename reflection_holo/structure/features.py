def _options() -> dict:
    return dict(
        termination=dict(value="bulk", label="ASSUMPTION B3",
                         note="unreconstructed bulk truncation, also on the feature walls"),
        dimer_reconstruction=dict(value="not enabled", status="NOT IMPLEMENTED: no Si(001)-(2x1) "
                                  "dimer geometry source has been read"),
        overlayer=dict(value=None, label="ASSUMPTION B7",
                       note="clean surface; the real surface is ion-milled (PROJECT_INPUT item 12)"),
        riser_relaxation=dict(value="none", label="ASSUMPTION",
                              note="no relaxation of the feature walls or terrace edges"),
    )


def _build(*, azimuth_uvw, azimuth_label, feature, extent_y_A, extent_z_A, depth_layers,
           lattice_parameter_A, lattice_label, ring_margin_A, vacuum_above_A):
    require_evidence_label(lattice_label, "lattice parameter (model_assumptions B2)",
                           accepted=LABEL_PREFIXES, qualified=True)
    a = float(lattice_parameter_A)
    if not (np.isfinite(a) and a > 0.0):
        raise ValueError(f"lattice_parameter_A must be finite and > 0, got {lattice_parameter_A!r}")
    q = a / 4.0
    require_evidence_label(azimuth_label, "azimuth (PROJECT_INPUT item 8)",
                           accepted=LABEL_PREFIXES, qualified=True)
    az = tuple(int(v) for v in azimuth_uvw)
    if not np.allclose(np.asarray(azimuth_uvw, float), az):
        raise ValueError("azimuth_uvw must be integer indices")
    frame = surface_frame(NORMAL_HKL, az)
    family = _family(az)
    checks.assert_frame(frame, NORMAL_HKL)
    if feature is not None:
        if not isinstance(feature, HalfTorus):
            raise TypeError("feature must be a reflection_holo.structure.shapes.HalfTorus")
        require_evidence_label(feature.label, "feature geometry (PROJECT_INPUT item 13)",
                               accepted=LABEL_PREFIXES, qualified=True)
    if isinstance(depth_layers, bool) or int(depth_layers) != depth_layers or depth_layers < 2:
        raise ValueError("depth_layers must be an integer >= 2")
    depth_layers = int(depth_layers)
    vac = float(vacuum_above_A)
    if not (np.isfinite(vac) and vac > 0.0):
        raise ValueError("vacuum_above_A must be finite and > 0")
    p, apl = _in_plane(a, family)
    my = _n_periods(extent_y_A, p, "extent_y_A")
    mz = _n_periods(extent_z_A, p, "extent_z_A")
    L = np.array([0.0, my * p, mz * p])
    l_s = depth_layers - 1
    x_s = l_s * q
    margin = float(ring_margin_A) if feature is not None else None

    N = 0
    if feature is not None:
        assert_ring_fits(feature, L[1], L[2], margin, p)                            # (b), (f)
        N = feature_layer_counts(feature, q)
        if feature.kind == "trench" and l_s - N < MIN_LAYERS_BELOW_FEATURE:
            raise ValueError(
                f"(f) depth_layers = {depth_layers} is too thin for a trench of minor radius "
                f"{feature.minor_radius_A} A ({N + 1} layers removed at most): need at least "
                f"{N + 1 + MIN_LAYERS_BELOW_FEATURE} layers")
    l_hi = l_s + (N if feature is not None and feature.kind == "ridge" else 0)

    # --- one continuous lattice, generated in chunks along z ---------------------------------
    tol = WINDOW_TOL_A
    parts, fparts, lparts = [], [], []
    n_chunks = max(1, int(np.ceil(L[2] / _CHUNK_Z_A)))
    edges = np.linspace(0.0, L[2], n_chunks + 1)
    for c in range(n_chunks):
        z0, z1 = edges[c], edges[c + 1]
        n, rs = _sites_in_box(frame, a, [-q, -p, z0 - p], [(l_hi + 1) * q, L[1] + p, z1 + p])
        layer = n[:, 2]
        win = ((rs[:, 1] >= -tol) & (rs[:, 1] < L[1] - tol) & (rs[:, 2] >= z0 - tol)
               & (rs[:, 2] < z1 - tol) & (layer >= 0) & (layer <= l_hi))
        n, rs, layer = n[win], rs[win], layer[win]
        base = layer <= l_s
        if feature is None:
            keep, fsite = base, np.zeros(len(layer), bool)
        else:
            inside = feature.contains((layer - l_s) * q, rs[:, 1], rs[:, 2])
            if feature.kind == "trench":
                fsite = base & inside
                keep = base & ~inside
            else:
                fsite = (layer > l_s) & inside
                keep = base | fsite
        parts.append(rs[keep])
        lparts.append(layer[keep])
        fparts.append(rs[fsite])
    rs = np.concatenate(parts)
    layer = np.concatenate(lparts)
    fs = np.concatenate(fparts) if fparts else np.zeros((0, 3))
    for arr in (rs, fs):
        arr[:, 1:][np.abs(arr[:, 1:]) < tol] = 0.0                  # snap boundary rows to 0
    order = np.lexsort((rs[:, 1], rs[:, 2], rs[:, 0]))
    rs, layer = rs[order], layer[order]
    fs = fs[np.lexsort((fs[:, 1], fs[:, 2], fs[:, 0]))] if len(fs) else fs
    L[0] = float(rs[:, 0].max()) + vac
    cell = np.diag(L)

    req = dict(a_A=a, depth_layers=depth_layers, periods_y=my, periods_z=mz,
               atoms_per_layer_per_cell=apl, ring_margin_A=margin, min_ring_margin_A=float(p),
               height_map_grid_A=HEIGHT_MAP_GRID_A, family=family)
    s = Si001FeatureStructure(positions_A=rs, species=np.full(rs.shape[0], "Si"),
                              Z=np.full(rs.shape[0], 14, dtype=np.int64), cell_A=cell,
                              pbc=(False, True, True), frame=frame, layer_index=layer,
                              crystal_origin_slab_A=np.zeros(3), feature=feature,
                              feature_sites_A=fs, request=req, metadata={})
    rec = verify_feature_structure(s)

    # --- metadata (keys shared with Si001Structure where forward.cell reads them) --------------
    pos_hash = hashlib.sha256(np.ascontiguousarray(rs, dtype="<f8").tobytes()).hexdigest()
    top_layers = np.array([x_s + v for v in (rec.get("height_map", {})
                                             .get("built_top_range_A", [0.0, 0.0]))])
    feature_md = None
    if feature is not None:
        feature_md = dict(
            shape="reflection_holo.structure.shapes.HalfTorus", kind=feature.kind,
            center_y_A=feature.center_y_A, center_z_A=feature.center_z_A,
            major_radius_A=feature.major_radius_A, minor_radius_A=feature.minor_radius_A,
            label=feature.label, source=feature.source, project_input="item 13",
            x_surface_A=x_s, flat_top_layer_index=l_s,
            n_removed=int(len(fs)) if feature.kind == "trench" else 0,
            n_added=int(len(fs)) if feature.kind == "ridge" else 0,
            max_layers_changed=N if feature.kind == "ridge" else N + 1,
            top_layer_x_range_A=[float(top_layers[0]), float(top_layers[1])],
            rule=("sites of the flat slab with contains(x - x_surface, y, z) removed"
                  if feature.kind == "trench" else
                  "sites of the same lattice above the flat top layer with contains(x - x_surface, "
                  "y, z) added"))
    s.metadata = dict(
        schema="reflection_holo.structure.features/1",
        builder=("reflection_holo.structure.features.build_si001_with_feature" if feature is not None
                 else "reflection_holo.structure.features.build_si001_flat_reference"),
        package_version=reflection_holo.__version__, units="angstrom",
        surface=dict(hkl=list(NORMAL_HKL), outward_normal="[001]",
                     label="PROJECT_INPUT item 11 (Si(001), supplied by Ali 2026-09-22)"),
        azimuth=dict(uvw=list(az), family=family, label=azimuth_label, project_input="item 8"),
        frame=dict(convention="x = outward normal, z = beam azimuth, y = z x x "
                              "(docs/physics_conventions.md)",
                   x_hat_crystal=frame.x_hat.tolist(), y_hat_crystal=frame.y_hat.tolist(),
                   z_hat_crystal=frame.z_hat.tolist(), crystal_origin_slab_A=[0.0, 0.0, 0.0]),
        lattice=dict(a_A=a, a_label=lattice_label, basis="constants.DIAMOND_BASIS (SM02)",
                     layer_spacing_A=q, nearest_neighbour_A=nearest_neighbour_distance_A(a),
                     in_plane_period_A=float(p), one_continuous_lattice=True),
        cell=dict(vectors_A=cell.tolist(), pbc=[False, True, True], vacuum_above_A=vac,
                  note="x is not periodic; bottom layer at x = 0; vacuum_above_A above the highest "
                       "atom; y and z are integer numbers of in-plane periods"),
        # compatibility with forward.cell.build_reflection_cell: ONE flat terrace (the surface that
        # carries the feature); the feature itself is NOT a terrace (see "feature")
        staircase=dict(kind="none: one flat terrace carrying a surface feature", edges=None,
                       staircase_axis="y", edge_axis="z", terrace_layers=[0],
                       terrace_widths_periods=[my], boundary_step_layers=0,
                       net_height_change_layers=0),
        terrace_map=[dict(index=0, s_range_A=[0.0, float(L[1])], width_periods=my,
                          top_layer_relative=0, top_layer_index=l_s, top_height_A=x_s,
                          n_atoms=int(rs.shape[0]),
                          note="the flat (001) surface; the feature's top-layer range is in "
                               "metadata['feature']")],
        steps=[],
        feature=feature_md,
        options=_options(),
        depth_layers=depth_layers, periods_y=my, periods_z=mz,
        atom_count=int(rs.shape[0]), expected_atom_count=rec["count"]["expected"],
        tolerances_A=dict(position=POSITION_TOL_A, window=WINDOW_TOL_A,
                          duplicate_distance=checks.DUPLICATE_DIST_A,
                          ring_margin_min=float(p), height_map_exclusion=a / np.sqrt(2.0),
                          count_shell=a / 8.0),
        checks={k: v for k, v in rec.items() if k != "assertions_passed"},
        assertions_passed=rec["assertions_passed"],
        positions_sha256=pos_hash,
    )
    return s


def build_si001_with_feature(*, azimuth_uvw, azimuth_label: str, feature: HalfTorus,
                             extent_y_A: float, extent_z_A: float, depth_layers: int,
                             lattice_parameter_A: float, lattice_label: str,
                             ring_margin_A: float, vacuum_above_A: float) -> Si001FeatureStructure:
    """Si(001) slab with a half-torus trench or ridge; assertions (a) to (g) run inside.

    Every argument is required (keyword-only, no defaults):

    azimuth_uvw, azimuth_label  beam azimuth (PROJECT_INPUT item 8; [110] or [100] families) and
                                its evidence label
    feature                     HalfTorus (PROJECT_INPUT item 13, carrying its label and source);
                                centre in the cell's (y, z) coordinates
    extent_y_A, extent_z_A      periodic cell lengths; each must be an integer number of in-plane
                                periods (a for <100>, a/sqrt(2) for <110>), else refused
    depth_layers                number of (001) layers of the flat slab (bottom layer at x = 0,
                                flat top layer at x_surface = (depth_layers - 1) a/4)
    lattice_parameter_A, lattice_label  the lattice parameter and its label (e.g. A_SI_A,
                                "ASSUMPTION B2")
    ring_margin_A               stated clearance between the ring's bounding box and the periodic
                                cell edges; must be >= one in-plane period
    vacuum_above_A              vacuum above the highest atom in the (non-periodic) x box
    """
    if feature is None:
        raise ValueError("feature is required (PROJECT_INPUT item 13); the flat reference is "
                         "build_si001_flat_reference")
    return _build(azimuth_uvw=azimuth_uvw, azimuth_label=azimuth_label, feature=feature,
                  extent_y_A=extent_y_A, extent_z_A=extent_z_A, depth_layers=depth_layers,
                  lattice_parameter_A=lattice_parameter_A, lattice_label=lattice_label,
                  ring_margin_A=ring_margin_A, vacuum_above_A=vacuum_above_A)


def build_si001_flat_reference(*, azimuth_uvw, azimuth_label: str, extent_y_A: float,
                               extent_z_A: float, depth_layers: int, lattice_parameter_A: float,
                               lattice_label: str, vacuum_above_A: float) -> Si001FeatureStructure:
    """The same slab WITHOUT the feature (same lattice, origin, window and layers), for the
    flat-surface reference run; assertions (a), (b), (c), (g) and a flat top layer."""
    return _build(azimuth_uvw=azimuth_uvw, azimuth_label=azimuth_label, feature=None,
                  extent_y_A=extent_y_A, extent_z_A=extent_z_A, depth_layers=depth_layers,
                  lattice_parameter_A=lattice_parameter_A, lattice_label=lattice_label,
                  ring_margin_A=None, vacuum_above_A=vacuum_above_A)
