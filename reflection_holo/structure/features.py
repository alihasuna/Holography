def _flat_count(req: dict) -> int:
    return int(req["atoms_per_layer_per_cell"] * req["periods_y"] * req["periods_z"]
               * req["depth_layers"])


def independent_feature_site_count(feature: HalfTorus, frame: SurfaceFrame, a_A: float,
                                   l_s: int) -> int:
    """Number of lattice sites the feature changes, from a SEPARATE enumeration over the ring's
    bounding box only (not the chunked cell generation)."""
    q = a_A / 4.0
    N = feature_layer_counts(feature, q)
    y0, y1, z0, z1 = _ring_box(feature)
    lo_l, hi_l = (l_s - N - 1, l_s) if feature.kind == "trench" else (l_s + 1, l_s + N + 1)
    n, rs = _sites_in_box(frame, a_A, [lo_l * q, y0 - 1.0, z0 - 1.0],
                          [hi_l * q, y1 + 1.0, z1 + 1.0])
    lay = n[:, 2]
    m = (lay >= lo_l) & (lay <= hi_l)
    x_rel = (lay[m] - l_s) * q
    return int(np.count_nonzero(feature.contains(x_rel, rs[m, 1], rs[m, 2])))


def verify_feature_structure(s: Si001FeatureStructure) -> dict:
    """Run assertions (a) to (g) on the atoms of ``s`` (everything recomputed from the positions
    and the request; the stored layer index is not trusted). Returns the records; raises
    StructureAssertionError on the first failure."""
    req = s.request
    a, q = req["a_A"], req["a_A"] / 4.0
    l_s = req["depth_layers"] - 1
    L = np.diag(np.asarray(s.cell_A, float))
    per = [None, float(L[1]), float(L[2])]
    pos = np.asarray(s.positions_A, float)
    feat = s.feature
    rec, passed = {}, []

    checks.assert_frame(s.frame, NORMAL_HKL)                                        # (g)
    passed.append("(g) frame right-handed, x = outward normal [001], beam azimuth in the surface")

    checks.assert_on_lattice_sites(pos, s.frame, s.crystal_origin_slab_A, a)        # (a)
    layer = _quarter_coords(pos, s.frame, a)[:, 2]
    assert_feature_rule(pos, layer, feat, l_s, q)
    passed.append("(a) every atom on a site of one bulk diamond lattice and obeying the feature "
                  "rule at its site")

    if feat is not None:                                                            # (b) margin
        rec["ring_fit"] = assert_ring_fits(feat, L[1], L[2], req["ring_margin_A"],
                                           req["min_ring_margin_A"])
    checks.assert_half_open_window(pos[:, 1], L[1], "y")                            # (b)
    checks.assert_half_open_window(pos[:, 2], L[2], "z")
    flat = _flat_count(req)
    if feat is None:
        n_feat_indep, expected = 0, flat
    else:
        n_feat_indep = independent_feature_site_count(feat, s.frame, a, l_s)
        expected = flat - n_feat_indep if feat.kind == "trench" else flat + n_feat_indep
    checks.assert_no_duplicates_and_count(pos, per, expected)
    rec["count"] = dict(flat_slab_count=flat, feature_sites_independent=n_feat_indep,
                        expected=expected, built=int(pos.shape[0]))
    passed.append("(b) half-open periodic window, no duplicates under the PBC, atom count = flat "
                  "slab -/+ independently enumerated feature sites"
                  + ("; ring inside the cell with the stated margin" if feat is not None else ""))

    floor = l_s
    if feat is not None and feat.kind == "trench" and len(s.feature_sites_A):
        floor = int(np.rint(np.asarray(s.feature_sites_A)[:, 0] / q).min()) - 1
    interior = (layer >= 1) & (layer <= floor - 1)
    i, j, _, _ = checks.assert_min_distance_and_coordination(pos, per, a, interior)  # (c)
    coord = np.bincount(i, minlength=pos.shape[0])
    if np.any(coord == 0):
        raise StructureAssertionError(f"(c) {int(np.sum(coord == 0))} isolated atom(s) (no "
                                      f"neighbour at a sqrt(3)/4)")
    if feat is not None and feat.kind == "ridge":
        added = layer > l_s
        below = np.zeros(pos.shape[0], bool)
        down = layer[j] == layer[i] - 1
        below[i[down]] = True
        if np.any(added & ~below):
            raise StructureAssertionError(f"(c) {int(np.sum(added & ~below))} ridge atom(s) not "
                                          f"bonded to the layer below")
    rec["coordination_histogram"] = {int(k): int(v) for k, v in
                                     zip(*np.unique(coord, return_counts=True))}
    passed.append("(c) minimum distance = a*sqrt(3)/4; interior atoms 4-coordinated; no isolated "
                  "atom" + ("; every ridge atom bonded to the layer below"
                            if feat is not None and feat.kind == "ridge" else ""))

    if feat is not None:
        n_feat = abs(int(pos.shape[0]) - flat)
        rec["volume_count"] = assert_feature_count(n_feat, feat, a)                  # (d)
        passed.append("(d) removed/added count = half-torus volume x atom density within "
                      "n (a/8) S")
        rec["height_map"] = assert_height_map(pos, s.frame, a, l_s, feat, L[1], L[2],
                                              req["height_map_grid_A"])              # (e)
        passed.append("(e) top-layer height map of the built atoms = layer_height_A (a/4) beyond "
                      "a/sqrt(2) from the ring boundary")
        rec["inside"] = assert_feature_inside(s.feature_sites_A, feat, l_s, q, L,
                                              req["ring_margin_A"])                  # (f)
        passed.append("(f) feature fully inside the cell")
    else:
        if np.max(layer) != l_s:
            raise StructureAssertionError("(e) flat reference: top layer is not l_s")
    rec["assertions_passed"] = passed
    return rec


