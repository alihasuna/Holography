@dataclass
class Si001FeatureStructure:
    """Result of :func:`build_si001_with_feature` (field names shared with Si001Structure where the
    meaning is the same, so forward.cell.build_reflection_cell accepts it)."""
    positions_A: np.ndarray            # (N, 3) slab frame, angstrom
    species: np.ndarray                # (N,) "Si"
    Z: np.ndarray                      # (N,) 14
    cell_A: np.ndarray                 # (3, 3) rows = cell vectors (slab frame)
    pbc: tuple[bool, bool, bool]       # (x, y, z) = (False, True, True)
    frame: SurfaceFrame
    layer_index: np.ndarray            # (N,) (001) layer l, x = l a/4
    crystal_origin_slab_A: np.ndarray  # (3,) = 0: crystal origin at the slab origin
    feature: HalfTorus | None          # None for the flat reference
    feature_sites_A: np.ndarray        # removed (trench) or added (ridge) sites, (M, 3) slab frame
    request: dict                      # the builder arguments needed to re-verify the structure
    metadata: dict

    @property
    def n_atoms(self) -> int:
        return int(self.positions_A.shape[0])

    @property
    def periodic_lengths_A(self):
        return [None, float(self.cell_A[1, 1]), float(self.cell_A[2, 2])]


