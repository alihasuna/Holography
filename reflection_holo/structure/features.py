def assert_ring_fits(feature: HalfTorus, L_y: float, L_z: float, margin_A: float,
                     min_margin_A: float) -> dict:
    """(b)/(f) the ring (outer radius R + r) fits inside the periodic window with the margin."""
    if not (np.isfinite(margin_A) and margin_A >= min_margin_A):
        raise StructureAssertionError(
            f"(b) ring_margin_A = {margin_A!r} A is below the stated minimum {min_margin_A:.6f} A "
            f"(one in-plane period): y and z are periodic, the ring must stay clear of its images")
    y0, y1, z0, z1 = _ring_box(feature)
    gaps = dict(y_low=y0, y_high=L_y - y1, z_low=z0, z_high=L_z - z1)
    bad = {k: v for k, v in gaps.items() if v < margin_A}
    if bad:
        raise StructureAssertionError(
            f"(f) the ring (centre ({feature.center_y_A}, {feature.center_z_A}) A, outer radius "
            f"{feature.major_radius_A + feature.minor_radius_A} A) does not fit inside the "
            f"periodic cell {L_y:.4f} x {L_z:.4f} A with the margin {margin_A} A: gaps {bad}")
    return dict(gaps_A=gaps, margin_A=float(margin_A), min_margin_A=float(min_margin_A),
                image_separation_A=float(min(L_y, L_z) - 2 * (feature.major_radius_A
                                                               + feature.minor_radius_A)))


def assert_feature_rule(positions_A, layer, feature: HalfTorus | None, l_s: int,
                        q_A: float) -> None:
    """(a) every atom obeys the feature rule at its own site: slab sites (l <= l_s) not removed,
    ridge sites (l > l_s) inside the half torus."""
    pos = np.asarray(positions_A, float)
    layer = np.asarray(layer)
    if np.any(layer < 0):
        raise StructureAssertionError("(a) atom below the slab bottom layer")
    if feature is None:
        if np.any(layer > l_s):
            raise StructureAssertionError("(a) flat reference: atom above the flat top layer")
        return
    x_rel = (layer - l_s) * q_A
    inside = feature.contains(x_rel, pos[:, 1], pos[:, 2])
    base = layer <= l_s
    if feature.kind == "trench":
        bad = ~base | inside
    else:
        bad = ~base & ~inside
    if np.any(bad):
        i = int(np.nonzero(bad)[0][0])
        raise StructureAssertionError(
            f"(a) {int(bad.sum())} atom(s) violate the {feature.kind} rule at their site; atom {i} "
            f"at {pos[i].tolist()} (layer {int(layer[i])})")


def feature_count_expectation(feature: HalfTorus, a_A: float) -> dict:
    """(d) n V, the tolerance n (a/8) S and the recorded flat-face bias (module docstring)."""
    R, r = feature.major_radius_A, feature.minor_radius_A
    n = 8.0 / a_A ** 3
    V = np.pi ** 2 * R * r ** 2
    S_curved = 2.0 * np.pi ** 2 * R * r
    S_flat = 4.0 * np.pi * R * r
    shell = a_A / 8.0
    tol = n * shell * (S_curved + S_flat)
    bias = n * shell * S_flat * (1.0 if feature.kind == "trench" else -1.0)
    return dict(atom_density_per_A3=n, half_volume_A3=V, expected_count=n * V,
                surface_curved_A2=S_curved, surface_flat_A2=S_flat, shell_A=shell,
                tolerance_count=tol, relative_tolerance=tol / (n * V),
                flat_face_bias_count=bias,
                rule="|N - n V| <= n (a/8) (S_curved + S_flat); DERIVED_HERE order-of-magnitude "
                     "bound set by the surface-to-volume ratio (module docstring (d))")


def assert_feature_count(n_feature: int, feature: HalfTorus, a_A: float) -> dict:
    e = feature_count_expectation(feature, a_A)
    dev = float(n_feature) - e["expected_count"]
    if abs(dev) > e["tolerance_count"]:
        raise StructureAssertionError(
            f"(d) {feature.kind} changes {n_feature} atoms; half-torus volume x density = "
            f"{e['expected_count']:.1f}, deviation {dev:+.1f} exceeds the tolerance "
            f"{e['tolerance_count']:.1f} (n (a/8) S, relative {e['relative_tolerance']:.3f})")
    return dict(e, measured_count=int(n_feature), deviation=dev,
                deviation_after_flat_face_bias=dev - e["flat_face_bias_count"])


def contour_distance_A(feature: HalfTorus, q_A: float, y, z) -> np.ndarray:
    """In-plane distance from (y, z) to the ring boundary: the circles rho = R +- s_n where
    layer_height_A jumps (s_n = sqrt(r^2 - (n q)^2) for the layers the feature changes)."""
    N = feature_layer_counts(feature, q_A)
    ns = np.arange(1, N + 1) if feature.kind == "ridge" else np.arange(0, N + 1)
    s = np.sqrt(feature.minor_radius_A ** 2 - (ns * q_A) ** 2)
    d = np.hypot(np.asarray(y, float) - feature.center_y_A,
                 np.asarray(z, float) - feature.center_z_A) - feature.major_radius_A
    dist = np.full(np.shape(d), np.inf)
    for sv in s:
        dist = np.minimum(dist, np.minimum(np.abs(d - sv), np.abs(d + sv)))
    return dist


def top_layer_height_map(positions_A, frame: SurfaceFrame, a_A: float, l_s: int,
                         y_grid_A, z_grid_A, L_y: float, L_z: float,
                         layer_range: tuple[int, int]) -> np.ndarray:
    """Top-layer height relative to the flat top layer (A) on the (y, z) grid, from the BUILT
    atoms (module docstring (e)): per layer, the lattice site nearest to each grid point in (y, z)
    is looked up among the built atoms (periodic in y and z); the top layer is the highest present
    layer in ``layer_range`` (inclusive). Raises if no layer of the range is present somewhere."""
    from scipy.spatial import cKDTree

    q = a_A / 4.0
    Y, Zg = np.meshgrid(np.asarray(y_grid_A, float), np.asarray(z_grid_A, float), indexing="ij")
    P = np.column_stack([Y.ravel(), Zg.ravel()])
    lo_l, hi_l = int(layer_range[0]), int(layer_range[1])
    pos = np.asarray(positions_A, float)
    sel = (np.rint(pos[:, 0] / q) >= lo_l) & (np.rint(pos[:, 0] / q) <= hi_l)
    built = np.unique(_keys(_quarter_coords(pos[sel], frame, a_A)))
    pad = 2.0 * a_A
    n, rs = _sites_in_box(frame, a_A, [lo_l * q - q, P[:, 0].min() - pad, P[:, 1].min() - pad],
                          [hi_l * q + q, P[:, 0].max() + pad, P[:, 1].max() + pad])
    wrapped = rs.copy()
    wrapped[:, 1] = np.mod(wrapped[:, 1], L_y)
    wrapped[:, 2] = np.mod(wrapped[:, 2], L_z)
    for ax, L in ((1, L_y), (2, L_z)):              # snap images of the window edge onto 0
        wrapped[np.abs(wrapped[:, ax] - L) < WINDOW_TOL_A, ax] = 0.0
    present_all = np.isin(_keys(_quarter_coords(wrapped, frame, a_A)), built)
    top = np.full(P.shape[0], np.iinfo(np.int64).min, dtype=np.int64)
    for l in range(lo_l, hi_l + 1):
        m = n[:, 2] == l
        if not np.any(m):
            continue
        tree = cKDTree(rs[m][:, 1:])
        _, idx = tree.query(P)
        top = np.where(present_all[m][idx], l, top)
    if np.any(top == np.iinfo(np.int64).min):
        raise StructureAssertionError(f"(e) no layer in {layer_range} is present at "
                                      f"{int(np.sum(top == np.iinfo(np.int64).min))} grid points")
    return ((top - l_s) * q).reshape(Y.shape)


def height_map_grid(feature: HalfTorus, L_y: float, L_z: float, step_A: float):
    """(y, z) grid over the ring's bounding box plus HEIGHT_MAP_PAD_A, clipped to the window."""
    y0, y1, z0, z1 = _ring_box(feature)
    ys = np.arange(max(0.0, y0 - HEIGHT_MAP_PAD_A), min(L_y, y1 + HEIGHT_MAP_PAD_A), step_A)
    zs = np.arange(max(0.0, z0 - HEIGHT_MAP_PAD_A), min(L_z, z1 + HEIGHT_MAP_PAD_A), step_A)
    return ys, zs


def assert_height_map(positions_A, frame: SurfaceFrame, a_A: float, l_s: int,
                      feature: HalfTorus, L_y: float, L_z: float, step_A: float) -> dict:
    """(e) height map from the built atoms equals layer_height_A beyond one in-layer lattice
    spacing a/sqrt(2) from the ring boundary; returns the statistics."""
    q = a_A / 4.0
    N = feature_layer_counts(feature, q)
    ys, zs = height_map_grid(feature, L_y, L_z, step_A)
    rng = (l_s - N - 2, l_s + N + 1)
    h = top_layer_height_map(positions_A, frame, a_A, l_s, ys, zs, L_y, L_z, rng)
    Y, Zg = np.meshgrid(ys, zs, indexing="ij")
    ideal = feature.layer_height_A(Y, Zg, layer_spacing_A=q)
    dist = contour_distance_A(feature, q, Y, Zg)
    spacing = a_A / np.sqrt(2.0)
    far = dist > spacing
    mism = np.abs(h - ideal) > POSITION_TOL_A
    bad = far & mism
    if np.any(bad):
        i = np.unravel_index(int(np.argmax(bad)), bad.shape)
        raise StructureAssertionError(
            f"(e) the top-layer height map of the built atoms differs from layer_height_A at "
            f"{int(bad.sum())} grid point(s) more than {spacing:.4f} A from the ring boundary; "
            f"first at (y, z) = ({Y[i]:.3f}, {Zg[i]:.3f}) A: built {h[i]:+.5f} A, ideal "
            f"{ideal[i]:+.5f} A")
    near = ~far
    footprint = feature.half_thickness_A(Y, Zg) > 0
    return dict(grid_step_A=float(step_A), n_points=int(h.size), n_checked=int(far.sum()),
                n_checked_inside_ring=int((far & footprint).sum()),
                n_near_boundary=int(near.sum()),
                n_disagree_near_boundary=int((near & mism).sum()),
                fraction_disagree_near_boundary=float((near & mism).sum() / max(near.sum(), 1)),
                fraction_disagree_inside_ring_footprint=float(
                    (footprint & mism).sum() / max(footprint.sum(), 1)),
                exclusion_distance_A=float(spacing),
                exclusion_rule="grid points within a/sqrt(2) of any circle where layer_height_A "
                               "jumps (rims and every a/4 terrace edge of the ring) are excluded",
                built_top_range_A=[float(h.min()), float(h.max())],
                ideal_top_range_A=[float(ideal.min()), float(ideal.max())])


def assert_feature_inside(feature_sites_A, feature: HalfTorus, l_s: int, q_A: float,
                          L: np.ndarray, margin_A: float) -> dict:
    """(f) measured on the feature sites: inside the ring's bounding box, clear of the periodic
    edges by the margin, deepest removed layer >= MIN_LAYERS_BELOW_FEATURE, ridge top below the box
    top."""
    fs = np.asarray(feature_sites_A, float)
    if fs.shape[0] == 0:
        raise StructureAssertionError("(f) the feature changes no lattice site")
    y0, y1, z0, z1 = _ring_box(feature)
    t = POSITION_TOL_A
    if (fs[:, 1].min() < y0 - t or fs[:, 1].max() > y1 + t or fs[:, 2].min() < z0 - t
            or fs[:, 2].max() > z1 + t):
        raise StructureAssertionError("(f) feature sites outside the ring's bounding box")
    if (fs[:, 1].min() < margin_A or fs[:, 1].max() > L[1] - margin_A
            or fs[:, 2].min() < margin_A or fs[:, 2].max() > L[2] - margin_A):
        raise StructureAssertionError("(f) feature sites closer than the margin to a periodic edge")
    lay = np.rint(fs[:, 0] / q_A).astype(np.int64)
    out = dict(feature_site_layers=[int(lay.min()), int(lay.max())],
               feature_site_y_range_A=[float(fs[:, 1].min()), float(fs[:, 1].max())],
               feature_site_z_range_A=[float(fs[:, 2].min()), float(fs[:, 2].max())])
    if feature.kind == "trench":
        if lay.min() < MIN_LAYERS_BELOW_FEATURE or lay.max() > l_s:
            raise StructureAssertionError(
                f"(f) trench removes layers {lay.min()}..{lay.max()}: it must stay within the slab "
                f"with at least {MIN_LAYERS_BELOW_FEATURE} intact layers below (0..{l_s})")
        out["intact_layers_below_trench"] = int(lay.min())
    else:
        if lay.min() <= l_s or (lay.max() + 1) * q_A > L[0]:
            raise StructureAssertionError("(f) ridge sites must lie above the flat top layer and "
                                          "below the top of the box")
        out["box_top_clearance_A"] = float(L[0] - lay.max() * q_A)
    return out


