def _family(az) -> str:
    fam = next((f for f, s in _AZIMUTHS.items() if az in s), None)
    if fam is None:
        raise ValueError(f"azimuth {az}: PROJECT_INPUT item 8 allows only the [110] or [100] "
                         f"families for Si(001)")
    return fam


def _in_plane(a_A: float, family: str) -> tuple[float, int]:
    """(period p along y and z, atoms per (001) layer per p x p cell)."""
    return (a_A / np.sqrt(2.0), 1) if family == "<110>" else (a_A, 2)


def _n_periods(extent_A, p, name) -> int:
    e = float(extent_A)
    if not (np.isfinite(e) and e > 0):
        raise ValueError(f"{name} must be finite and > 0")
    m = int(round(e / p))
    if m < 1 or abs(e - m * p) > PERIOD_TOL_A:
        raise ValueError(f"{name} = {e!r} A is not an integer number of in-plane lattice periods "
                         f"p = {p:.9f} A (the cell must be periodic); nearest allowed values "
                         f"{max(m, 1) * p:.9f} or {(max(m, 1) + 1) * p:.9f} A")
    return m


def feature_layer_counts(feature: HalfTorus, q_A: float) -> int:
    """Largest number of a/4 layers the feature can change: ceil(r/q) - 1 (layers n = 1..N added for
    the ridge, layers n = 0..-(N) i.e. N + 1 layers for the trench; shapes.py rule)."""
    return int(np.ceil(feature.minor_radius_A / q_A)) - 1


def _ring_box(feature: HalfTorus):
    Ro = feature.major_radius_A + feature.minor_radius_A
    return (feature.center_y_A - Ro, feature.center_y_A + Ro,
            feature.center_z_A - Ro, feature.center_z_A + Ro)


def _sites_in_box(frame: SurfaceFrame, a_A: float, lo_slab, hi_slab):
    """Integer a/4 crystal coordinates and slab positions of the ONE lattice (origin at the slab
    origin) covering the slab box [lo, hi] (with the one-cell margin of diamond_sites_quarter)."""
    lo, hi = np.asarray(lo_slab, float), np.asarray(hi_slab, float)
    corners = np.array([[x, y, z] for x in (lo[0], hi[0]) for y in (lo[1], hi[1])
                        for z in (lo[2], hi[2])])
    cc = frame.to_crystal(corners)
    n = diamond_sites_quarter(cc.min(axis=0), cc.max(axis=0), a_A)
    return n, frame.to_slab(n.astype(float) * (a_A / 4.0))


def _keys(n: np.ndarray) -> np.ndarray:
    n = np.asarray(n, np.int64) + _KEY_OFF
    if n.min() < 0 or n.max() >= 2 * _KEY_OFF:
        raise ValueError("site coordinates exceed the key range")
    return (n[:, 0] << 42) | (n[:, 1] << 21) | n[:, 2]


def _quarter_coords(pos_slab, frame, a_A):
    """Integer a/4 crystal coordinates of slab positions (after assertion (a) they are exact)."""
    return np.rint(frame.to_crystal(np.asarray(pos_slab, float)) / (a_A / 4.0)).astype(np.int64)


